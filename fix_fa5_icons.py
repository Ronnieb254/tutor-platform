# Remove entries where old == new (no actual change needed)
RENAMES = {k: v for k, v in RENAMES.items() if k != v}

# Sort by length descending so longer names match first (e.g. fa-times-circle before fa-times)
SORTED = sorted(RENAMES.items(), key=lambda x: -len(x[0]))


def fix_file(filepath):
    with open(filepath, 'r', encoding='utf-8', errors='ignore') as fh:
        original = fh.read()
    
    content = original
    
    # Replace each old icon name with new, using word boundaries
    # Match: fa-oldname (as a class, preceded by space or quote)
    for old_name, new_name in SORTED:
        # Use word boundary to avoid partial matches
        # e.g. fa-times should not match fa-times-circle
        pattern = r'(?<![\w-])' + re.escape(old_name) + r'(?![\w-])'
        content = re.sub(pattern, new_name, content)
    
    if content != original:
        with open(filepath, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(content)
        return True
    return False


def main():
    files = glob.glob('resources/views/**/*.blade.php', recursive=True)
    fixed = 0
    for f in sorted(files):
        if fix_file(f):
            fixed += 1
            print(f'  fixed  {f}')
    print(f'\nDone. {fixed} file(s) updated.')


if __name__ == '__main__':
    main()
